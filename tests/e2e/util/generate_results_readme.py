def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate tests/e2e/results/README.md from discovered result folders."
    )
    parser.add_argument(
        "results_dir",
        nargs="?",
        default="tests/e2e/results",
        help="Path to the results directory (default: tests/e2e/results)",
    )
    args = parser.parse_args()

    results_dir = Path(args.results_dir).resolve()
    if not results_dir.exists():
        raise SystemExit(f"Results directory not found: {results_dir}")

    readme_path = results_dir / "README.md"
    readme_path.write_text(render_readme(results_dir), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
