    lines.append("Top-level keys: `all`, `video`, `audio`, `summary`.")
    lines.append("- `all`/`video`/`audio`: spacing/jitter statistics (min/mean/max/median/std, percentiles).")
    lines.append("- `summary`: packet counts and capture duration.")
    lines.append("")
    lines.append("#### resource_usage.csv Columns")
    lines.append("")
    lines.append("| Column | Description |")
    lines.append("|--------|-------------|")
    lines.append("| `timestamp_ms` | Milliseconds since sampling began |")
    lines.append("| `cpu_percent` | System-wide CPU usage (%) |")
    lines.append("| `ram_percent` | System RAM usage (%) |")
    lines.append("| `ram_mb` | System RAM usage (MiB) |")
    lines.append("| `proc_cpu_*` | Per-process CPU usage when tracked (e.g., `proc_cpu_obs`) |")
    lines.append("| `gpu_percent` | GPU usage (%) when available |")
    lines.append("| `gpu_mem_percent` | GPU memory usage (%) when available |")
    lines.append("| `gpu_mem_mb` | GPU memory usage (MiB) when available |")
    lines.append("")
    lines.append("#### resource.json Structure")
    lines.append("")
    lines.append("Summary keys include:")
    lines.append("- `duration_ms`, `sample_interval_ms`, `sample_count`")
    lines.append("- `cpu_percent`, `ram_percent`, `ram_mb` (each has min/median/mean/max/sample_count)")
    lines.append("- `gpu_available`, `gpu_type`, optional GPU stats")
    lines.append("- `process_cpu_percent` for tracked PIDs (same stats shape)")
    lines.append("")
    lines.append("### Configuration Snapshot")
    lines.append("")
    lines.append("- `config_used/` - Captured OBS profile + scene configuration used for the run.")
    lines.append("")
    lines.append("## Running Tests")
    lines.append("")
    lines.append("### Single Scenario")
    lines.append("")
